import os
import shutil
import datetime
from pathlib import Path

def weekly_maintenance():
    """Automated weekly maintenance"""
    base_path = Path("h:\\")
    
    print("🤖 Starting weekly maintenance...")
    
    # Clean build caches
    cache_dirs = [".next", "__pycache__", ".gradio"]
    cleaned_caches = 0
    
    for cache_dir in cache_dirs:
        cache_path = base_path / cache_dir
        if cache_path.exists():
            try:
                shutil.rmtree(cache_path)
                print(f"✅ Cleaned {cache_dir}")
                cleaned_caches += 1
            except Exception as e:
                print(f"⚠️ Could not clean {cache_dir}: {e}")
    
    # Archive old health reports
    health_files = list(base_path.glob("HEALTH_SUMMARY_*.txt"))
    cutoff = datetime.datetime.now() - datetime.timedelta(days=30)
    archived_reports = 0
    
    for health_file in health_files:
        if health_file.stat().st_mtime < cutoff.timestamp():
            archive_dir = base_path / "🗂️_EMPIRE_ARCHIVES_🗂️" / "health_reports_archive"
            archive_dir.mkdir(parents=True, exist_ok=True)
            try:
                shutil.move(str(health_file), str(archive_dir / health_file.name))
                archived_reports += 1
            except Exception as e:
                print(f"⚠️ Could not archive {health_file.name}: {e}")
    
    # Rotate memory crystal backups (keep newest 10 per type)
    memory_crystals_path = base_path / "memory_crystals"
    if memory_crystals_path.exists():
        backup_files = list(memory_crystals_path.glob("*.backup*"))
        if len(backup_files) > 30:  # If we have too many backups
            backup_files.sort(key=lambda f: f.stat().st_mtime, reverse=True)
            old_backups = backup_files[30:]  # Keep newest 30
            
            archive_backup_dir = base_path / "🗂️_EMPIRE_ARCHIVES_🗂️" / "memory_crystal_backups"
            archive_backup_dir.mkdir(parents=True, exist_ok=True)
            
            for old_backup in old_backups:
                try:
                    shutil.move(str(old_backup), str(archive_backup_dir / old_backup.name))
                except Exception as e:
                    print(f"⚠️ Could not archive backup {old_backup.name}: {e}")
    
    print(f"🎊 Weekly maintenance complete!")
    print(f"   📦 Cleaned {cleaned_caches} cache directories")
    print(f"   📊 Archived {archived_reports} old health reports") 
    print(f"   💎 Memory crystal backups optimized")
    print(f"   🏆 Empire organization maintained at LEGENDARY level!")

